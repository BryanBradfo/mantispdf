/**
 * What the build knows that the service worker must follow: the pdf.js version (the worker's URL) and one
 * content id per runtime folder (vite.config.ts hashes public/fonts-runtime and public/ocr-runtime).
 */
export interface PwaBuildIds {
  pdfjsVersion: string;
  fontsId: string;
  ocrId: string;
}

/**
 * Same-origin runtime folders fetched on first use, never precached (fonts 33 MB, OCR 24 MB). Their file
 * names never change (fonts.json, worker.min.js, core/*, NotoSans*.ttf, *.traineddata.gz), so the cache
 * NAME carries the folder's content id: when a deploy changes any file, the new worker uses a new, empty
 * cache (files are fetched again on first use) and the cleanup script deletes the older ones on activate.
 * Until then CacheFirst is right: a name only ever holds one version of the folder.
 */
export const RUNTIME_PREFIXES = { fonts: "mantis-fonts-runtime", ocr: "mantis-ocr-runtime" } as const;

export const runtimeCacheNames = (ids: PwaBuildIds) => ({
  fonts: `${RUNTIME_PREFIXES.fonts}-${ids.fontsId}`,
  ocr: `${RUNTIME_PREFIXES.ocr}-${ids.ocrId}`,
});

/** The script sw.js imports (emitted by vite.config.ts): its name follows the ids, so it changes with them. */
export const runtimeCleanupFile = (ids: PwaBuildIds) => `sw-runtime-${ids.fontsId}-${ids.ocrId}.js`;

/** On activate, delete every runtime cache of an older build (any name with our prefixes but not `keep`). */
export function runtimeCleanupScript(keep: string[]): string {
  return `// Generated by vite.config.ts (src/pwa/config.ts): deletes the runtime caches of older builds.
self.addEventListener("activate", (event) => {
  const keep = ${JSON.stringify(keep)};
  event.waitUntil(
    caches.keys().then((names) =>
      Promise.all(names.filter((n) => /^mantis-(fonts|ocr)-runtime/.test(n) && !keep.includes(n)).map((n) => caches.delete(n))),
    ),
  );
});
`;
}

const runtimeCacheOptions = (cacheName: string, maxEntries: number) => ({
  cacheName,
  // A full disk drops these caches rather than failing the request (the file is fetched again next time).
  expiration: { maxEntries, purgeOnQuotaError: true },
  cacheableResponse: { statuses: [200] },
});

/** The largest precached file is the WASM engine (about 3.5 MB). */
const MAX_PRECACHED_BYTES = 6 * 1024 * 1024;

/**
 * Workbox `generateSW` options. Precache: the app code (every JS chunk, so every tool works offline), CSS,
 * the WASM, the UI fonts (woff2), the pdf.js worker, the favicons and the shell. Navigations go to the
 * network (prerendered pages stay fresh) and fall back to the precached shell offline, which renders any
 * route; a cached prerendered page is never served, since it would name the chunks of an older deploy.
 *
 * vite-plugin-pwa writes the service worker when `vite build` closes, BEFORE the postbuild prerender
 * writes dist/shell.html; at that point dist/index.html is that shell, byte for byte (buildSeoFiles copies
 * it), so its entry is precached under the shell's URL. scripts/check-pwa.mjs verifies the revision.
 */
interface PrecacheEntry {
  url: string;
  revision: string | null;
  size: number;
}

/** For the build ids of `vite build`; see vite.config.ts. */
export function workboxOptions(ids: PwaBuildIds) {
  const names = runtimeCacheNames(ids);
  return {
    globPatterns: [
      "index.html",
      "assets/**/*.{js,css,wasm,woff2}",
      PDF_WORKER_FILE,
      "favicon.svg",
      "favicon-32.png",
      "apple-touch-icon.png",
    ],
    // Desktop-only chunks (the Tauri updater and settings) are never loaded on the web.
    globIgnores: ["assets/DesktopSettingsDialog-*.js", "assets/DesktopUpdateBanner-*.js"],
    maximumFileSizeToCacheInBytes: MAX_PRECACHED_BYTES,
    manifestTransforms: [
      async (entries: PrecacheEntry[]) => ({
        manifest: entries.map((e) =>
          e.url === "index.html"
            ? { ...e, url: SHELL_URL }
            : e.url === PDF_WORKER_FILE
              ? // The URL the app requests (src/lib/pdf.ts), query included.
                { ...e, url: pdfWorkerPath(ids.pdfjsVersion).slice(1) }
              : e,
        ),
        warnings: [],
      }),
    ],
    importScripts: [runtimeCleanupFile(ids)],
    navigateFallback: null,
    cleanupOutdatedCaches: true,
    // registerType "prompt": the new worker waits until the person chooses Reload (src/pwa/swUpdate.ts).
    skipWaiting: false,
    clientsClaim: false,
    runtimeCaching: [
      {
        urlPattern: ({ request }: { request: Request }) => request.mode === "navigate",
        handler: "NetworkOnly" as const,
        options: { precacheFallback: { fallbackURL: SHELL_URL } },
      },
      // Workbox writes these callbacks into sw.js as source text: literals only, no closure.
      // Same origin only: never cache another origin (there is none to cache today).
      {
        urlPattern: ({ url, sameOrigin }: { url: URL; sameOrigin: boolean }) => sameOrigin && url.pathname.startsWith("/fonts-runtime/"),
        handler: "CacheFirst" as const,
        options: runtimeCacheOptions(names.fonts, 40),
      },
      {
        urlPattern: ({ url, sameOrigin }: { url: URL; sameOrigin: boolean }) => sameOrigin && url.pathname.startsWith("/ocr-runtime/"),
        handler: "CacheFirst" as const,
        options: runtimeCacheOptions(names.ocr, 30),
      },
    ],
  };
}
