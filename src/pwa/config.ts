/** Same-origin runtime folders fetched on first use: cached then, never precached (fonts 33 MB, OCR 24 MB). */
export const RUNTIME_CACHES = [
  { prefix: "/fonts-runtime/", cacheName: "mantis-fonts-runtime", maxEntries: 40 },
  { prefix: "/ocr-runtime/", cacheName: "mantis-ocr-runtime", maxEntries: 30 },
] as const;

function runtimeCacheOptions({ cacheName, maxEntries }: (typeof RUNTIME_CACHES)[number]) {
  return { cacheName, expiration: { maxEntries }, cacheableResponse: { statuses: [200] } };
}

/** The largest precached file is the WASM engine (about 3.5 MB). */
const MAX_PRECACHED_BYTES = 6 * 1024 * 1024;

/**
 * Workbox `generateSW` options. Precache: the app code (every JS chunk, so every tool works offline), CSS,
 * the WASM, the UI fonts (woff2), the pdf.js worker, the favicons and the shell. Navigations go to the
 * network (prerendered pages stay fresh) and fall back to the precached shell offline, which renders any
 * route; a cached prerendered page is never served, since it would name the chunks of an older deploy.
 *
 * vite-plugin-pwa writes the service worker when `vite build` closes, BEFORE the postbuild prerender
 * writes dist/shell.html; at that point dist/index.html is that shell, byte for byte (buildSeoFiles copies
 * it), so its entry is precached under the shell's URL. scripts/check-pwa.mjs verifies the revision.
 */
interface PrecacheEntry {
  url: string;
  revision: string | null;
  size: number;
}

export const workboxOptions = {
  globPatterns: [
    "index.html",
    "assets/**/*.{js,css,wasm,woff2}",
    "pdf.worker.min.mjs",
    "favicon.svg",
    "favicon-32.png",
    "apple-touch-icon.png",
  ],
  // Desktop-only chunks (the Tauri updater and settings) are never loaded on the web.
  globIgnores: ["assets/DesktopSettingsDialog-*.js", "assets/DesktopUpdateBanner-*.js"],
  maximumFileSizeToCacheInBytes: MAX_PRECACHED_BYTES,
  manifestTransforms: [
    async (entries: PrecacheEntry[]) => ({
      manifest: entries.map((e) => (e.url === "index.html" ? { ...e, url: SHELL_URL } : e)),
      warnings: [],
    }),
  ],
  navigateFallback: null,
  cleanupOutdatedCaches: true,
  // registerType "prompt": the new worker waits until the person chooses Reload (src/pwa/swUpdate.ts).
  skipWaiting: false,
  clientsClaim: false,
  runtimeCaching: [
    {
      urlPattern: ({ request }: { request: Request }) => request.mode === "navigate",
      handler: "NetworkOnly" as const,
      options: { precacheFallback: { fallbackURL: SHELL_URL } },
    },
    // Workbox writes these callbacks into sw.js as source text: literals only, no closure over RUNTIME_CACHES.
    // Same origin only: never cache another origin (there is none to cache today).
    {
      urlPattern: ({ url, sameOrigin }: { url: URL; sameOrigin: boolean }) => sameOrigin && url.pathname.startsWith("/fonts-runtime/"),
      handler: "CacheFirst" as const,
      options: runtimeCacheOptions(RUNTIME_CACHES[0]),
    },
    {
      urlPattern: ({ url, sameOrigin }: { url: URL; sameOrigin: boolean }) => sameOrigin && url.pathname.startsWith("/ocr-runtime/"),
      handler: "CacheFirst" as const,
      options: runtimeCacheOptions(RUNTIME_CACHES[1]),
    },
  ],
};
