// Regenerates the MantisPDF brand assets from assets/brand/mantis-source.jpeg:
// MantisMark / MantisHead path data, favicons, Open Graph images, and the Tauri icon source.
// Usage: node scripts/brand-assets.mjs [source.jpeg]   (then `npx tauri icon` runs on the 1024 px head)
// The traces, favicons and OG images are deterministic; `tauri icon` output is not byte-stable, so
// check `git status src-tauri/icons` after a run and `git checkout` it when only noise changed.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { inflateSync } from "node:zlib";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const potrace = require("potrace");
const Jimp = require("jimp");
const { Resvg } = require("@resvg/resvg-js");

const source = resolve(process.argv[2] ?? join(root, "assets/brand/mantis-source.jpeg"));
const TRACE = { threshold: 128, turdSize: 8, optTolerance: 0.4, color: "currentColor", background: "transparent" };
// Bust crop in source pixels: head, antennae and the raised forelegs, so the mantis reads even at 32 px.
const HEAD = { x: 280, y: 120, w: 1250, h: 1250 };
const INK = "#f2f2f2";
// Small uses (header, footer, title bar at 16-36 px, favicons): trace a downscaled crop, coarser, so the path stays light.
const SMALL = { px: 320, turdSize: 24, optTolerance: 3 };

const trace = (input, extra = {}) =>
  new Promise((ok, fail) => potrace.trace(input, { ...TRACE, ...extra }, (e, svg) => (e ? fail(e) : ok(svg))));

/** Path data out of potrace's svg, rounded to 1 decimal and compacted. */
function compactPath(svg) {
  const d = /\sd="([^"]+)"/.exec(svg)?.[1];
  if (!d) throw new Error("potrace produced no path");
  const num = (n) => String(Math.round(parseFloat(n) * 10) / 10);
  return d
    .replace(/-?\d+(?:\.\d+)?/g, num)
    .replace(/\s*,\s*/g, ",")
    .replace(/\s*([MCLZ])\s*/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

/** Integer bounding box of the absolute coordinates in a path (control points included). */
function bbox(d) {
  const n = d.match(/-?\d+(?:\.\d+)?/g).map(Number);
  const xs = n.filter((_, i) => i % 2 === 0);
  const ys = n.filter((_, i) => i % 2 === 1);
  const x = Math.floor(Math.min(...xs));
  const y = Math.floor(Math.min(...ys));
  return { x, y, w: Math.ceil(Math.max(...xs)) - x, h: Math.ceil(Math.max(...ys)) - y };
}

function component(name, doc, box, d) {
  return `// Generated by scripts/brand-assets.mjs from assets/brand/mantis-source.jpeg. Do not edit.
const PATH =
  "${d}";

interface Props {
  className?: string;
  /** Accessible name. Without it the mark is decorative (aria-hidden). */
  title?: string;
}

/** ${doc} */
export function ${name}({ className, title }: Props) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="${box.x} ${box.y} ${box.w} ${box.h}"
      fill="currentColor"
      className={className}
      {...(title ? { role: "img" } : { "aria-hidden": true })}
    >
      {title && <title>{title}</title>}
      <path d={PATH} fillRule="evenodd" />
    </svg>
  );
}
`;
}

/** Fontsource ships woff only; resvg reads sfnt, so unwrap the woff container to a TTF. */
function woffToSfnt(file) {
  const w = readFileSync(file);
  if (w.toString("latin1", 0, 4) !== "wOFF") throw new Error(`${file} is not a woff`);
  const n = w.readUInt16BE(12);
  const entries = [];
  for (let i = 0; i < n; i++) {
    const o = 44 + i * 20;
    const [offset, comp, orig, sum] = [4, 8, 12, 16].map((k) => w.readUInt32BE(o + k));
    const data = comp < orig ? inflateSync(w.subarray(offset, offset + comp)) : w.subarray(offset, offset + orig);
    entries.push({ tag: w.subarray(o, o + 4), sum, data });
  }
  let pow = 1;
  while (pow * 2 <= n) pow *= 2;
  const head = Buffer.alloc(12 + n * 16);
  w.copy(head, 0, 4, 8);
  head.writeUInt16BE(n, 4);
  head.writeUInt16BE(pow * 16, 6);
  head.writeUInt16BE(Math.log2(pow), 8);
  head.writeUInt16BE(n * 16 - pow * 16, 10);
  let pos = head.length;
  const bodies = entries.map((e, i) => {
    e.tag.copy(head, 12 + i * 16);
    head.writeUInt32BE(e.sum, 12 + i * 16 + 4);
    head.writeUInt32BE(pos, 12 + i * 16 + 8);
    head.writeUInt32BE(e.data.length, 12 + i * 16 + 12);
    const padded = Buffer.concat([e.data, Buffer.alloc((4 - (e.data.length % 4)) % 4)]);
    pos += padded.length;
    return padded;
  });
  return Buffer.concat([head, ...bodies]);
}

const png = (svg, width, fontFiles = []) =>
  new Resvg(svg, {
    fitTo: { mode: "width", value: width },
    font: { fontFiles, loadSystemFonts: false, defaultFontFamily: "Oswald" },
  })
    .render()
    .asPng();

const escapeXml = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");

function tagline(locale) {
  const src = readFileSync(join(root, `src/i18n/locales/${locale}/home.ts`), "utf8");
  const raw = /^\s*tagline:\s*("(?:[^"\\]|\\.)*")/m.exec(src)?.[1];
  if (!raw) throw new Error(`no tagline in ${locale}/home.ts`);
  return JSON.parse(raw);
}

const write = (rel, data) => {
  const file = join(root, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, data);
  console.log(`wrote ${rel} (${data.length} bytes)`);
};

// 1. Traces: the whole drawing, and the head cropped from the same pixels.
const image = await Jimp.read(source);
const markD = compactPath(await trace(source));
const cropped = image.clone().crop(HEAD.x, HEAD.y, HEAD.w, HEAD.h);
const markBox = bbox(markD);
const small = cropped.clone().resize(SMALL.px, SMALL.px, Jimp.RESIZE_BICUBIC);
const headD = compactPath(await trace(await small.getBufferAsync(Jimp.MIME_PNG), { turdSize: SMALL.turdSize, optTolerance: SMALL.optTolerance }));
const headBox = { x: 0, y: 0, w: SMALL.px, h: SMALL.px };

write("src/components/brand/MantisMark.tsx", component("MantisMark", "The full mantis drawing, traced from the source art.", markBox, markD));
write("src/components/brand/MantisHead.tsx", component("MantisHead", "The mantis bust (head and forelegs), cropped from the same trace, for small sizes.", headBox, headD));

// 2. Favicons and app icons: bust centred on its own bounding box, on a black square with even padding.
function iconSvg(d, [bg, fg] = ["#000", "#fff"]) {
  const b = bbox(d);
  const side = Math.round(Math.max(b.w, b.h) * 1.1);
  const tx = (side - b.w) / 2 - b.x;
  const ty = (side - b.h) / 2 - b.y;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${side} ${side}"><rect width="${side}" height="${side}" fill="${bg}"/><g transform="translate(${tx} ${ty})" fill="${fg}"><path d="${d}" fill-rule="evenodd"/></g></svg>`;
}
const faviconSvg = iconSvg(headD);
const headSquare = iconSvg(headD);
write("public/favicon.svg", faviconSvg + "\n");
write("public/favicon-32.png", png(faviconSvg, 32));
write("public/apple-touch-icon.png", png(headSquare, 180));

// 3. Open Graph, one per locale: wordmark and tagline left, mark right, in Oswald.
const oswald = join(root, "node_modules/@fontsource/oswald/files");
const fontDir = mkdtempSync(join(tmpdir(), "mantis-oswald-"));
const iconDir = mkdtempSync(join(tmpdir(), "mantis-icon-"));
const fonts = [300, 500].map((wt) => {
  const out = join(fontDir, `oswald-${wt}.ttf`);
  writeFileSync(out, woffToSfnt(join(oswald, `oswald-latin-${wt}-normal.woff`)));
  return out;
});
const markH = 560;
const markW = Math.round((markBox.w / markBox.h) * markH);
const markX = 1200 - 60 - markW;
for (const locale of ["en", "fr"]) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
<rect width="1200" height="630" fill="#000"/>
<svg x="${markX}" y="35" width="${markW}" height="${markH}" viewBox="${markBox.x} ${markBox.y} ${markBox.w} ${markBox.h}" fill="#fff"><path d="${markD}" fill-rule="evenodd"/></svg>
<text x="72" y="320" font-family="Oswald" font-weight="500" font-size="120" fill="${INK}" letter-spacing="-2">MantisPDF</text>
<text x="76" y="400" font-family="Oswald" font-weight="300" font-size="44" fill="#a3a3a3">${escapeXml(tagline(locale))}</text>
</svg>`;
  write(`public/og-${locale}.png`, png(svg, 1200, fonts));
}

// 3b. README hero: the full mark and the wordmark, white on black, no tagline.
{
  const h = 460;
  const w = Math.round((markBox.w / markBox.h) * h);
  const gap = 56;
  const wordW = 410; // Oswald 500 at 112 px: "MantisPDF" is about 410 px wide
  const x0 = Math.round((1200 - (w + gap + wordW)) / 2);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="600" viewBox="0 0 1200 600">
<rect width="1200" height="600" fill="#000"/>
<svg x="${x0}" y="70" width="${w}" height="${h}" viewBox="${markBox.x} ${markBox.y} ${markBox.w} ${markBox.h}" fill="#fff"><path d="${markD}" fill-rule="evenodd"/></svg>
<text x="${x0 + w + gap}" y="338" font-family="Oswald" font-weight="500" font-size="112" fill="${INK}" letter-spacing="-2">MantisPDF</text>
</svg>`;
  write("docs/brand/readme-hero.png", png(svg, 1200, fonts));
}

// 4. Tauri icons from a 1024 px head (white on black).
const iconSource = join(iconDir, "head-1024.png");
writeFileSync(iconSource, png(headSquare, 1024));
execFileSync("npx", ["tauri", "icon", iconSource], { cwd: root, stdio: "inherit" });
rmSync(fontDir, { recursive: true, force: true });
rmSync(iconDir, { recursive: true, force: true });
